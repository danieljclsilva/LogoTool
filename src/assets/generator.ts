/**
 * Model-generator abstraction for synthetic asset provenance.
 *
 * A `ModelGenerator` produces GLB bytes without touching the network: the
 * only shipped implementation is `SyntheticModelGenerator`, a stub that
 * delegates byte production to an injected fixture function so tests can
 * build deterministic multi-mesh payloads. There is intentionally no Tripo
 * (or any remote-provider) implementation in this slice — external model
 * generation stays out of the offline Logo Station entirely.
 *
 * Portable: no imports, no Node fs/crypto, no browser/Three.js APIs.
 */

export interface GeneratorInput {
  prompt?: string;
  seed?: string;
  productId?: string;
  variantId?: string;
}

export interface GeneratorOutput {
  bytes: Uint8Array;
  generatedBy: string;
}

/** Provider abstraction: generated bytes plus their provenance label. */
export interface ModelGenerator {
  readonly provider: string;
  generate(input: GeneratorInput): Promise<GeneratorOutput>;
}

/**
 * Synthetic stub generator. Calls the injected `fixture` to obtain bytes
 * (sync or async), validates the result is a non-empty Uint8Array, and tags
 * it with a `generatedBy` label. Never performs I/O.
 */
export class SyntheticModelGenerator implements ModelGenerator {
  readonly provider = "synthetic";
  private readonly fixture: (
    input: GeneratorInput,
  ) => Uint8Array | Promise<Uint8Array>;
  private readonly label: string;

  constructor(
    fixture: (input: GeneratorInput) => Uint8Array | Promise<Uint8Array>,
    label = "synthetic-stub/0.1.0",
  ) {
    this.fixture = fixture;
    this.label = label;
  }

  async generate(input: GeneratorInput): Promise<GeneratorOutput> {
    const bytes = await this.fixture(input);
    if (!(bytes instanceof Uint8Array) || bytes.length === 0) {
      throw new Error(
        "SyntheticModelGenerator fixture must resolve a non-empty Uint8Array.",
      );
    }
    return { bytes, generatedBy: this.label };
  }
}
